-- Minimal demo schema reconstructed from the three workflow exports.
-- This is NOT a dump or migration of the original pilot database.
-- Run in a separate demo database. Existing tables are not altered.
BEGIN;

CREATE SCHEMA IF NOT EXISTS renaissance;

CREATE TABLE IF NOT EXISTS renaissance.events (
  event_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_name text NOT NULL
);

CREATE TABLE IF NOT EXISTS renaissance.suppliers (
  supplier_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_inn text NOT NULL UNIQUE CHECK (btrim(supplier_inn) <> ''),
  supplier_name text NOT NULL,
  bank_account text NOT NULL CHECK (btrim(bank_account) <> '')
);

CREATE TABLE IF NOT EXISTS renaissance.invoices (
  invoice_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_number text NOT NULL CHECK (btrim(invoice_number) <> ''),
  invoice_date date,
  supplier_name text,
  supplier_inn text NOT NULL REFERENCES renaissance.suppliers(supplier_inn),
  amount numeric(18, 2) NOT NULL CHECK (amount > 0),
  currency text,
  vat_amount numeric(18, 2),
  bank_account text NOT NULL CHECK (btrim(bank_account) <> ''),
  status text NOT NULL DEFAULT 'processed',
  event_id integer REFERENCES renaissance.events(event_id),
  expense_category text,
  version integer NOT NULL DEFAULT 1 CHECK (version > 0),
  approval_status text NOT NULL DEFAULT 'pending'
    CHECK (approval_status IN ('pending', 'approved', 'rejected')),
  decided_by text,
  decided_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (supplier_inn, invoice_number)
);

COMMIT;
